/**
 * Generates supabase/002_seed_doctypes.sql from the single source of truth
 * (src/lib/doctypes.data.mjs). Run after editing a field list or a prompt:
 *
 *   node scripts/build-seed-sql.mjs
 *
 * Dollar-quoting ($fdai$...$fdai$) is used so prompts containing quotes,
 * apostrophes and backslashes need no escaping at all.
 */

import fs from "node:fs";
import path from "node:path";
import { DOC_TYPE_DATA } from "../src/lib/doctypes.data.mjs";

const TAG = "$fdai$";

function q(value) {
  const s = typeof value === "string" ? value : JSON.stringify(value);
  if (s.includes(TAG)) {
    throw new Error(`Content contains the dollar-quote tag ${TAG}; change the tag in this script.`);
  }
  return `${TAG}${s}${TAG}`;
}

const rows = DOC_TYPE_DATA.map(
  (d) => `insert into public.doc_types (slug, label, description, fields, system_prompt, examples)
values (
  ${q(d.slug)},
  ${q(d.label)},
  ${q(d.description)},
  ${q(d.fields)}::jsonb,
  ${q(d.systemPrompt)},
  '[]'::jsonb
)
on conflict (slug) do update set
  label         = excluded.label,
  description   = excluded.description,
  fields        = excluded.fields,
  system_prompt = excluded.system_prompt,
  updated_at    = now();`,
).join("\n\n");

const header = `-- ===========================================================================
-- FDAI sprint 2.2 — seed the document catalogue
-- GENERATED by scripts/build-seed-sql.mjs — do not edit by hand.
-- Source of truth: src/lib/doctypes.data.mjs
--
-- Run 001_schema.sql first, then paste this into the Supabase SQL editor.
-- Re-running is safe: it upserts on slug.
--
-- NOTE: \`examples\` is seeded empty on purpose. The worked NDAs live in code
-- (src/lib/examples) and are stitched in at runtime, so this file stays small.
-- Paste the firm's own examples into the \`examples\` column when they exist:
--   [{"title": "...", "text": "..."}]
-- ===========================================================================

`;

const out = path.join(process.cwd(), "supabase/002_seed_doctypes.sql");
fs.writeFileSync(out, header + rows + "\n");
console.log(`wrote ${out} (${DOC_TYPE_DATA.length} doc type(s))`);
